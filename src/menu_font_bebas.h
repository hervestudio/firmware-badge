static int bbTextW(const char *s)
{
  int w = 0;
  for (; *s; s++)
    if (*s >= 32 && *s < 127)
      w += BB_GLYPHS[*s - 32].adv;
  return w;
}

static void bbPrint(int x, int y, const char *s, uint16_t col)
{
  for (; *s; s++)
  {
    if (*s < 32 || *s >= 127)
      continue;
    const BBGlyph &g = BB_GLYPHS[*s - 32];
    int stride = (g.w + 7) / 8;
    for (int gy = 0; gy < BB_H; gy++)
      for (int gx = 0; gx < g.w; gx++)
        if (BB_BITS[g.off + gy * stride + gx / 8] & (0x80 >> (gx & 7)))
          canvas->drawPixel(x + g.xoff + gx, y + gy, col);
    x += g.adv;
  }
}
